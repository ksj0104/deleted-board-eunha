export type RecordFile = {
  id: string;
  board: string;
  title: string;
  author: string;
  date: string;
  paragraphs: string[];
  comments?: { author: string; text: string; date?: string }[];
  photo?: { src: string; alt: string; caption: string };
  status?: string;
  attachment?: { title: string; columns: string[]; rows: string[][] };
  deleted?: boolean;
};
export type Question = {
  id: string;
  prompt: string;
  kind: "choice" | "code" | "order";
  options?: string[];
  placeholder?: string;
  evidenceCount: number;
};
export type Episode = {
  id: number;
  title: string;
  subtitle: string;
  mechanic: string;
  duration: string;
  date: string;
  intro: string;
  objective: string;
  records: RecordFile[];
  questions: Question[];
  hints: string[];
};
const record = (
  id: string,
  board: string,
  title: string,
  author: string,
  date: string,
  paragraphs: string[],
  extra: Partial<RecordFile> = {},
): RecordFile => ({ id, board, title, author, date, paragraphs, ...extra });
const choice = (
  id: string,
  prompt: string,
  options: string[],
  evidenceCount = 2,
): Question => ({ id, prompt, kind: "choice", options, evidenceCount });

