export function recordStats(record: RecordFile) {
  const hash = [...(record.id + record.title)].reduce(
    (sum, c) => (sum * 31 + c.charCodeAt(0)) >>> 0,
    7,
  );
  return {
    views: 32 + (hash % 570),
    likes: 1 + (hash % 23),
    color: ["#647b63", "#a0795b", "#68838c", "#8b7390", "#9b8860"][hash % 5],
  };
}
