export function inquiryDiscovered(
  episode: Episode,
  question: Question,
  progress: Progress,
) {
  return (
    progress.solved.includes(episode.id) ||
    !!progress.drafts[episode.id]?.[question.id] ||
    caseThreads[episode.id - 1].inquiries[question.id].discoveredBy.some((id) =>
      progress.read.includes(id),
    )
  );
}
